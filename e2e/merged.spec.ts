import { expect, test } from '@playwright/test'

test('merged rows share a supplier cell and still validate a price', async ({ page }) => {
  await page.goto('/play/merged')
  const cell = page.getByTestId('supplier-p1').locator('xpath=ancestor::td')
  await expect(cell).toHaveAttribute('rowspan', '2')
  await page.getByTestId('price-p1').fill('1001')
  await page.getByTestId('price-p1').blur()
  await expect(page.getByTestId('price-error-p1')).toContainText('1000')
  await page.getByTestId('only-active').check()
  await expect(page.getByTestId('name-p2')).toHaveCount(0)
  const span = await page.getByTestId('supplier-p1').locator('xpath=ancestor::td').getAttribute('rowspan')
  expect(span === null || span === '1').toBe(true)
})

test('a supplier name is one field, groups move, and a C-level price is the parent check', async ({ page }) => {
  await page.goto('/play/merged')
  await page.getByTestId('supplier-p1').fill('甲')
  await expect(page.getByTestId('names')).toHaveText('甲,供应商B')
  await page.getByTestId('up-sB').click()
  await expect(page.getByTestId('names')).toHaveText('供应商B,甲')
  await page.getByTestId('supplier-p3').fill('甲')
  await page.getByTestId('supplier-p3').blur()
  await expect(page.getByTestId('supplier-error-sB')).toContainText('重名')
  await page.getByTestId('add-product-sA').click()
  await expect(page.locator('[data-testid^="name-"]').filter({ hasText: '新产品' })).toHaveCount(1)
  await page.getByTestId('price-p3').fill('1001')
  await page.getByTestId('price-p3').blur()
  await expect(page.getByTestId('price-error-p3')).toHaveText('')
})

test('an empty supplier can be named and receive its first product', async ({ page }) => {
  await page.goto('/play/merged')
  await page.getByTestId('add-supplier').click()
  const addButtons = page.locator('[data-testid^="add-product-"]')
  await expect(addButtons).toHaveCount(3)
  const supplierId = (await addButtons.last().getAttribute('data-testid'))!.slice('add-product-'.length)
  const cell = page.getByTestId(`supplier-cell-${supplierId}`)
  await cell.getByRole('textbox', { name: '供应商名称' }).fill('新供应商')
  await expect(page.getByTestId('names')).toHaveText('供应商A,供应商B,新供应商')
  await expect(page.getByTestId(`empty-supplier-${supplierId}`)).toHaveText('暂无产品')
  await cell.getByRole('button', { name: '加产品' }).click()
  await expect(page.getByTestId(`empty-supplier-${supplierId}`)).toHaveCount(0)
  await expect(page.locator('[data-testid^="name-"]').filter({ hasText: '新产品' })).toHaveCount(1)
  await expect(page.locator('input[data-testid^="price-"]')).toHaveCount(4)
})

test('filtered empty groups keep their parent controls without rendering hidden product fields', async ({ page }) => {
  await page.goto('/play/merged')
  await page.getByTestId('active-p1').uncheck()
  await page.getByTestId('only-active').check()
  await expect(page.getByTestId('name-p1')).toHaveCount(0)
  await expect(page.getByTestId('name-p2')).toHaveCount(0)
  await expect(page.getByTestId('empty-supplier-sA')).toHaveText('没有在售产品')
  await expect(page.getByTestId('price-p1')).toHaveCount(0)
  await page.getByTestId('add-product-sA').click()
  await expect(page.getByTestId('empty-supplier-sA')).toHaveCount(0)
  await expect(page.locator('[data-testid^="name-"]').filter({ hasText: '新产品' })).toHaveCount(1)
  await page.getByTestId('only-active').uncheck()
  const cell = page.getByTestId('supplier-p1').locator('xpath=ancestor::td')
  await expect(cell).toHaveAttribute('rowspan', '3')
})

test('an empty supplier keeps its name error when the first product replaces its placeholder', async ({ page }) => {
  await page.goto('/play/merged')
  await page.getByTestId('add-supplier').click()
  const add = page.locator('[data-testid^="add-product-"]').last()
  const supplierId = (await add.getAttribute('data-testid'))!.slice('add-product-'.length)
  const cell = page.getByTestId(`supplier-cell-${supplierId}`)
  await cell.getByRole('textbox', { name: '供应商名称' }).fill('供应商A')
  await cell.getByRole('textbox', { name: '供应商名称' }).blur()
  await expect(page.getByTestId(`supplier-error-${supplierId}`)).toContainText('重名')
  await add.click()
  await expect(page.getByTestId(`empty-supplier-${supplierId}`)).toHaveCount(0)
  await expect(page.getByTestId(`supplier-error-${supplierId}`)).toContainText('重名')
  await cell.getByRole('textbox', { name: '供应商名称' }).fill('独立供应商')
  await cell.getByRole('textbox', { name: '供应商名称' }).blur()
  await expect(page.getByTestId(`supplier-error-${supplierId}`)).toHaveText('')
})

test('repeated additions retain the invalid product error rather than lending it to a new row', async ({ page }) => {
  await page.goto('/play/merged')
  await page.getByTestId('add-product-sA').click()
  const firstPrice = page.locator('input[data-testid^="price-"]').nth(2)
  const productId = (await firstPrice.getAttribute('data-testid'))!.slice('price-'.length)
  await firstPrice.fill('1001')
  await firstPrice.blur()
  await expect(page.getByTestId(`price-error-${productId}`)).toContainText('1000')
  await page.getByTestId('add-product-sA').click()
  await page.getByTestId('add-product-sB').click()
  const prices = page.locator('input[data-testid^="price-"]')
  await expect(prices).toHaveCount(6)
  const ids = await prices.evaluateAll(inputs => inputs.map(input => input.getAttribute('data-testid')))
  expect(new Set(ids).size).toBe(6)
  await expect(page.getByTestId(`price-${productId}`)).toHaveValue('1001')
  await expect(page.getByTestId(`price-error-${productId}`)).toContainText('1000')
  await expect(page.locator('[data-testid^="price-error-"]').filter({ hasText: '1000' })).toHaveCount(1)
})
