import { expect, test } from '@playwright/test'

test('merged rows share a supplier cell and still validate a price', async ({ page }) => {
  await page.goto('/play/merged')
  const cell = page.getByTestId('supplier-p1').locator('xpath=ancestor::td')
  await expect(cell).toHaveAttribute('rowspan', '2')
  await page.getByTestId('price-p1').fill('1001')
  await page.getByTestId('price-p1').blur()
  await expect(page.getByTestId('price-error-p1')).toContainText('1000')
  await page.getByTestId('only-active').check()
  await expect(page.getByTestId('name-p2')).toHaveCount(0)
  const span = await page.getByTestId('supplier-p1').locator('xpath=ancestor::td').getAttribute('rowspan')
  expect(span === null || span === '1').toBe(true)
})

test('a supplier name is one field, groups move, and a C-level price is the parent check', async ({ page }) => {
  await page.goto('/play/merged')
  await page.getByTestId('supplier-p1').fill('甲')
  await expect(page.getByTestId('names')).toHaveText('甲,供应商B')
  await page.getByTestId('up-sB').click()
  await expect(page.getByTestId('names')).toHaveText('供应商B,甲')
  await page.getByTestId('supplier-p3').fill('甲')
  await page.getByTestId('supplier-p3').blur()
  await expect(page.getByTestId('supplier-error-sB')).toContainText('重名')
  await page.getByTestId('add-product-sA').click()
  await expect(page.getByTestId('name-p-new')).toHaveText('新产品')
  await page.getByTestId('price-p3').fill('1001')
  await page.getByTestId('price-p3').blur()
  await expect(page.getByTestId('price-error-p3')).toHaveText('')
})
