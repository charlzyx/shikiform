import { expect, test } from '@playwright/test'

test('nested orders keep values when collapsed and the address survives closing the drawer', async ({ page }) => {
  await page.goto('/play/nested')
  const qty0 = page.getByTestId('order-0').locator('input')
  await qty0.fill('4')
  await page.getByTestId('toggle-orders').click()
  await expect(page.getByTestId('orders-collapsed')).toBeVisible()
  await page.getByTestId('toggle-orders').click()
  await expect(qty0).toHaveValue('4')
  await expect(page.getByTestId('order-1').locator('input')).toHaveCount(0)
  await expect(page.getByTestId('order-1')).toContainText('2')
  await page.getByTestId('edit-mode').click()
  await expect(page.getByTestId('order-0').locator('input')).toHaveCount(0)
  await expect(page.getByTestId('order-0')).toContainText('4')
  await page.getByTestId('open-drawer').click()
  await page.getByTestId('city').fill('苏州')
  await page.getByRole('dialog').getByRole('button', { name: '关闭' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByTestId('open-drawer').click()
  await expect(page.getByTestId('city')).toHaveValue('苏州')
})
