import { expect, test } from '@playwright/test'

test('orders: expanded line edits recompute totals, survive collapse, shipped order stays read-only', async ({ page }) => {
  await page.goto('/play/orders')
  const order = (no: string) => page.locator('table.sk-table').first().locator('> tbody > tr').filter({ hasText: no })
  const line = (sku: string) => page.locator('table.sk-table--sm > tbody > tr').filter({ hasText: sku })
  const expandBtn = (no: string) => order(no).getByRole('button', { name: /展开行|收起行/ })
  await expect(order('A001')).toContainText('26')
  await expandBtn('A001').click()
  const qty = line('pen').locator('input').first()
  await expect(qty).toHaveValue('1')
  await qty.fill('4')
  await qty.blur()
  await expect(line('pen')).toContainText('40')
  await expect(order('A001')).toContainText('56')
  await expandBtn('A001').click()
  await expandBtn('A001').click()
  await expect(line('pen').locator('input').first()).toHaveValue('4')
  await expandBtn('A002').click()
  await expect(line('box')).toBeVisible()
  await expect(line('box').locator('input')).toHaveCount(0)
  await page.getByRole('switch').first().click()
  await expect(line('pen').locator('input')).toHaveCount(0)
  await expect(line('pen')).toContainText('4')
})
