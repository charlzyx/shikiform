import { expect, test } from '@playwright/test'

test('orders: expanded line edits recompute totals, survive collapse, shipped order stays read-only', async ({ page }) => {
  await page.goto('/play/orders')
  const order = (id: string) => page.locator(`tr.ant-table-row[data-row-key="${id}"]`)
  const line = (id: string) => page.locator(`tr.ant-table-row[data-row-key="${id}"]`)
  await expect(order('o1')).toContainText('26')
  await order('o1').locator('.ant-table-row-expand-icon').click()
  const qty = line('i1').locator('input').first()
  await expect(qty).toHaveValue('1')
  await qty.fill('4')
  await qty.blur()
  await expect(line('i1')).toContainText('40')
  await expect(order('o1')).toContainText('56')
  await order('o1').locator('.ant-table-row-expand-icon').click()
  await order('o1').locator('.ant-table-row-expand-icon').click()
  await expect(line('i1').locator('input').first()).toHaveValue('4')
  await order('o2').locator('.ant-table-row-expand-icon').click()
  await expect(line('i3')).toBeVisible()
  await expect(line('i3').locator('input')).toHaveCount(0)
  await page.locator('.ant-switch').first().click()
  await expect(line('i1').locator('input')).toHaveCount(0)
  await expect(line('i1')).toContainText('4')
})
